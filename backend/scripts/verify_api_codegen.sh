repo_root="$(cd "${backend_dir}/.." && pwd)"

resolve_tool() {
  local variable_name="$1"
  local command_name="$2"
  local fallback="$3"
  local configured="${!variable_name:-}"
  if [[ -n "${configured}" && -x "${configured}" ]]; then
    printf '%s\n' "${configured}"
    return
  fi
  if command -v "${command_name}" >/dev/null 2>&1; then
    command -v "${command_name}"
    return
  fi
  if [[ -x "${fallback}" ]]; then
    printf '%s\n' "${fallback}"
    return
  fi
  printf 'missing required tool: %s\n' "${command_name}" >&2
  exit 1
}

select_sha256() {
  if command -v sha256sum >/dev/null 2>&1; then
    command -v sha256sum
    return
  fi
  if command -v shasum >/dev/null 2>&1; then
    command -v shasum
    return
  fi
  printf 'missing sha256sum or shasum\n' >&2
  exit 1
}

hz_bin="$(resolve_tool HZ_BIN hz "${HOME}/go/bin/hz")"
thriftgo_bin="$(resolve_tool THRIFTGO_BIN thriftgo "${HOME}/go/bin/thriftgo")"
sha256_bin="$(select_sha256)"
hz_version="$("${hz_bin}" --version 2>&1)"
thriftgo_version="$("${thriftgo_bin}" --version 2>&1)"
[[ "${hz_version}" == "hz version v0.9.7" ]] || {
  printf 'expected exact hz version v0.9.7, got %s\n' "${hz_version}" >&2
  exit 1
}
[[ "${thriftgo_version}" == "thriftgo 0.4.5" ]] || {
  printf 'expected exact thriftgo version 0.4.5, got %s\n' "${thriftgo_version}" >&2
  exit 1
}

